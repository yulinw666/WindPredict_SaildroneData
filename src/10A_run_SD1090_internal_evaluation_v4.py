def infer_modern(a, c, utility, torch, nn, F, DataLoader, TensorDataset,
                 frozen, modern_dir: Path, predictions_dir: Path,
                 device, batch_size: int, use_amp: bool):
    model_classes = a.build_model_classes(torch, nn, F)
    loader = c.make_loader(
        torch, DataLoader, TensorDataset,
        frozen["test"]["X"], frozen["test"]["y"],
        batch_size=batch_size, shuffle=False,
        pin_memory=(device.type == "cuda"), seed=0,
    )
    criterion = nn.MSELoss(reduction="mean")
    out_all = {}
    predictions_dir.mkdir(parents=True, exist_ok=True)

    for model_name in MODERN_MODELS:
        out_all[model_name] = {}
        safe = model_name.replace("-", "_")
        log(f"\n[MODERN TEST] {model_name}")
        for seed in SEEDS:
            p = modern_dir / "models" / f"{safe}_seed{seed}.pt"
            if not p.exists():
                raise FileNotFoundError(f"Frozen 09C checkpoint missing: {p}")
            ckpt = torch_load(torch, p, "cpu")
            model = a.instantiate_model(
                model_classes, model_name, dict(ckpt["config"]),
                seq_len=frozen["lookback"],
                n_features=len(frozen["feature_names"]),
                n_horizons=len(frozen["horizons"]),
                n_targets=len(frozen["target_names"]),
            ).to(device)
            model.load_state_dict(ckpt["state_dict"], strict=True)
            ev = c.evaluate_loader(
                utility, torch, model, loader, device=device,
                criterion=criterion, target_mean=frozen["target_mean"],
                target_std=frozen["target_std"], use_amp=use_amp,
            )
            pred = np.asarray(ev["pred_raw"], dtype=np.float32)
            truth = np.asarray(ev["truth_raw"], dtype=np.float32)
            if not np.allclose(truth, frozen["test_y_raw"], atol=2e-5, rtol=0):
                raise RuntimeError(f"{model_name}/seed{seed}: test truth mismatch")
            out_all[model_name][seed] = pred
            payload = {
                "pred_raw": pred,
                "truth_raw": truth,
                "apparent_earth_raw": apparent_from_joint(truth).astype(np.float32),
            }
            if frozen["test_target_time_ns"] is not None:
                payload["target_time_ns"] = frozen["test_target_time_ns"]
            np.savez_compressed(predictions_dir / f"test_{safe}_seed{seed}.npz", **payload)
            log(f"  seed={seed} | test mean AW={ev['mean_AW_RMSE_mps']:.6f} m/s")
            del model
            if device.type == "cuda":
                torch.cuda.empty_cache()
    return out_all


