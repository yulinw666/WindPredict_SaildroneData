PRED_KEYS = ["pred_raw", "y_pred_raw", "prediction_raw", "predictions_raw", "joint_pred_raw", "yhat_raw", "y_pred", "pred"]
TRUTH_KEYS = ["truth_raw", "y_raw", "y_true_raw", "target_raw", "targets_raw", "y_true", "truth"]


def discover_generic(base: Path, model: str, seed: Optional[int]):
    """
    Find conventional-baseline TEST predictions without substring collisions.

    IMPORTANT
    ---------
    The old v3 matcher used:
        "lstm" in normalized_filename

    which also matches:
        CNN_LSTM_seed_..._test_predictions.npz

    Therefore LSTM could accidentally load CNN-LSTM predictions and the two
    rows became numerically identical.  v4 uses the exact filename convention
    written by 16A_run_conventional_neural_baselines_final.py:

        GRU_seed_<seed>_test_predictions.npz
        LSTM_seed_<seed>_test_predictions.npz
        CNN_LSTM_seed_<seed>_test_predictions.npz

    If multiple exact candidates are found, abort rather than silently pick one.
    """
    if not base.exists():
        return []

    safe = model.replace("-", "_")

    if seed is not None:
        exact_name = f"{safe}_seed_{seed}_test_predictions.npz"
        candidates = [
            p for p in base.rglob("*.npz")
            if p.name.lower() == exact_name.lower()
        ]

        if len(candidates) > 1:
            raise RuntimeError(
                f"Ambiguous frozen TEST predictions for {model}, seed={seed}:\n"
                + "\n".join(str(p) for p in sorted(candidates))
                + "\nPoint --conventional-dir to the unique final 16A output directory."
            )

        return sorted(candidates)

    # Fallback discovery for a model-level frozen TEST artifact.  Require the
    # normalized filename to START with the exact model token, so LSTM cannot
    # match CNN-LSTM.
    model_token = norm_text(safe)
    out = []

    for p in base.rglob("*.npz"):
        n = norm_text(p.name)

        if not n.startswith(model_token):
            continue

        if "test" not in n and "internalevaluation" not in n:
            continue

        out.append(p)

    return sorted(out)


def load_generic_joint(path: Path, truth_ref):
    with np.load(path, allow_pickle=False) as z:
        pred = first_key(z, PRED_KEYS).astype(np.float32)
        truth = first_key(z, TRUTH_KEYS, required=False)
    if pred.ndim == 2 and pred.shape[1] == 30:
        pred = pred.reshape(-1, 5, 6)
    if pred.shape != truth_ref.shape:
        raise RuntimeError(f"{path}: pred shape {pred.shape} != {truth_ref.shape}")
    if truth is not None:
        truth = np.asarray(truth, dtype=np.float32)
        if truth.ndim == 2 and truth.shape[1] == 30:
            truth = truth.reshape(-1, 5, 6)
        if truth.shape != truth_ref.shape or not np.allclose(truth, truth_ref, atol=2e-5, rtol=0):
            raise RuntimeError(f"{path}: stored truth does not match frozen SD1090 test")
    return pred


def load_conventional(conventional_dir: Path, truth_ref, allow_missing=False):
    result, missing = {}, []
    used_paths = {}

    for model in CONVENTIONAL_MODELS:
        seed_map = {}

        for seed in SEEDS:
            candidates = discover_generic(conventional_dir, model, seed)

            if candidates:
                chosen = candidates[0].resolve()

                # Defensive check: the same NPZ must never represent two
                # different conventional model names.
                if chosen in used_paths and used_paths[chosen] != model:
                    raise RuntimeError(
                        f"Conventional prediction collision: {chosen}\n"
                        f"already assigned to {used_paths[chosen]}, "
                        f"but now also matched {model}."
                    )

                used_paths[chosen] = model
                seed_map[seed] = load_generic_joint(chosen, truth_ref)
                log(f"[CONVENTIONAL TEST] {model} seed={seed} | {chosen}")
        if not seed_map:
            # Accept one already-frozen model-level TEST NPZ as a fallback.
            candidates = discover_generic(conventional_dir, model, None)
            if candidates:
                seed_map[-1] = load_generic_joint(candidates[0], truth_ref)
                log(f"[CONVENTIONAL TEST] {model} single frozen run | {candidates[0]}")
        if not seed_map:
            msg = f"No frozen TEST prediction NPZ found for {model} under {conventional_dir}"
            missing.append(msg)
            if not allow_missing:
                raise FileNotFoundError(msg + "\nPoint --conventional-dir to the folder containing the final frozen test predictions.")
        else:
            result[model] = seed_map

    # Cross-model sanity audit.  Exact equality across every element for the
    # same seed is suspicious enough to abort, because independently trained
    # GRU/LSTM/CNN-LSTM models should not produce bitwise-identical tensors.
    models_present = list(result.keys())

    for i in range(len(models_present)):
        for j in range(i + 1, len(models_present)):
            a_name = models_present[i]
            b_name = models_present[j]
            common_seeds = sorted(
                set(result[a_name]).intersection(result[b_name])
            )

            for seed in common_seeds:
                if np.array_equal(
                    result[a_name][seed],
                    result[b_name][seed],
                ):
                    raise RuntimeError(
                        "Conventional-baseline sanity check failed: "
                        f"{a_name} and {b_name} have bitwise-identical TEST "
                        f"predictions for seed={seed}. Check file discovery."
                    )

    return result, missing


