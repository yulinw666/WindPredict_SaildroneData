def first_key(z, keys, required=True):
    for k in keys:
        if k in z:
            return np.asarray(z[k])
    if required:
        raise KeyError(f"None of {keys} exists; available={list(z.files)}")
    return None


def discover_pc_test_file(base: Path, seed: int) -> Optional[Path]:
    if not base.exists():
        return None
    exact = [
        base / f"15E_VH_seed_{seed}_test_predictions.npz",
        base / f"15E_VH_seed_{seed}_internal_evaluation_predictions.npz",
    ]
    for p in exact:
        if p.exists():
            return p
    candidates = []
    for p in base.rglob("*.npz"):
        n = norm_text(p.name)
        if str(seed) in n and ("test" in n or "internalevaluation" in n) and ("15e" in n or "vh" in n or "physics" in n):
            candidates.append(p)
    return sorted(candidates)[0] if candidates else None


def load_pc_test(physics_dir: Path, truth_ref):
    out = {}
    for seed in SEEDS:
        p = discover_pc_test_file(physics_dir, seed)
        if p is None:
            raise FileNotFoundError(
                f"Final Physics-Compact TEST prediction not found for seed {seed} under:\n{physics_dir}\n"
                "Expected TEST NPZ keys: y_raw, frozen_truewind, joint_vessel_hdg.\n"
                "Validation files are intentionally not reused."
            )
        with np.load(p, allow_pickle=False) as z:
            truth = first_key(z, ["y_raw", "truth_raw", "target_raw"]).astype(np.float32)
            wind = first_key(z, ["frozen_truewind", "truewind", "pred_wind_raw", "wind_raw"]).astype(np.float32)
            motion = first_key(z, ["joint_vessel_hdg", "vessel_hdg", "pred_motion_hdg_raw", "motion_hdg_raw"]).astype(np.float32)
        if truth.shape != truth_ref.shape or not np.allclose(truth, truth_ref, atol=2e-5, rtol=0):
            raise RuntimeError(f"{p}: truth is not the frozen SD1090 test split")
        if wind.shape != (len(truth_ref), 5, 2) or motion.shape != (len(truth_ref), 5, 4):
            raise RuntimeError(f"{p}: unexpected branch shapes wind={wind.shape}, motion={motion.shape}")
        out[seed] = {"path": p, "wind": wind, "motion": motion, "pred": make_joint(wind, motion)}
        log(f"[PC TEST] seed={seed} | {p}")
    return out


