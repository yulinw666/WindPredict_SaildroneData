def aggregate_seed(df):
    metric_cols = [c for c in df.columns if c.startswith("mean_")]
    rows = []
    for model, g in df.groupby("model", sort=False):
        r = {"model": model, "seed_count": int(len(g))}
        for c in metric_cols:
            v = pd.to_numeric(g[c], errors="coerce")
            r[c] = float(v.mean())
            r[f"std_{c}"] = float(v.std(ddof=1)) if len(v) > 1 else 0.0
        rows.append(r)
    return pd.DataFrame(rows)


def aggregate_horizon(df):
    rows = []
    for (model, horizon), g in df.groupby(
        ["model", "horizon_min"],
        sort=False,
    ):
        row = {
            "model": model,
            "horizon_min": int(horizon),
            "seed_count": int(g["seed"].nunique()),
        }
        for metric in ALL_METRIC_COLUMNS:
            vals = pd.to_numeric(g[metric], errors="coerce")
            row[f"mean_{metric}"] = float(vals.mean())
            row[f"std_{metric}"] = (
                float(vals.std(ddof=1))
                if len(vals) > 1
                else 0.0
            )
        rows.append(row)
    return pd.DataFrame(rows)


def write_all_horizon_outputs(tables_dir: Path, hs: pd.DataFrame) -> None:
    """
    Save complete horizon-wise results for ALL evaluated models.

    Outputs include:
      - long-form mean/std summary for every model x horizon x metric
      - one wide CSV for each metric (1,2,3,5,10 min columns)
      - controlled branch-ablation AW-RMSE by horizon
      - modern-model AW-RMSE by horizon

    The five-horizon averages are kept only as additional summary tables.
    """
    tables_dir.mkdir(parents=True, exist_ok=True)

    order = [
        "Persistence",
        "Dual Ridge",
        "GRU",
        "LSTM",
        "CNN-LSTM",
        "DLinear",
        "TimeMixer",
        "iTransformer",
        "PatchTST",
        "Wind enhanced",
        "Motion enhanced",
        "Physics-Compact",
    ]

    hs2 = hs.copy()
    hs2["_order"] = hs2["model"].map({m: i for i, m in enumerate(order)})
    hs2 = hs2.sort_values(["_order", "horizon_min"]).drop(columns="_order")

    # Full long-form file: this is the master horizon-wise result file.
    hs2.to_csv(
        tables_dir / "internal_ALL_models_ALL_horizons_summary.csv",
        index=False,
        encoding="utf-8-sig",
    )

    metric_map = {
        "U_RMSE_mps": "U_RMSE",
        "V_RMSE_mps": "V_RMSE",
        "wind_vector_RMSE_mps": "Wind_vector_RMSE",
        "wind_speed_RMSE_mps": "Wind_speed_RMSE",
        "Vessel_East_RMSE_mps": "Vessel_East_RMSE",
        "Vessel_North_RMSE_mps": "Vessel_North_RMSE",
        "vessel_vector_RMSE_mps": "Vessel_vector_RMSE",
        "SOG_RMSE_mps": "SOG_RMSE",
        "App_U_RMSE_mps": "App_U_RMSE",
        "App_V_RMSE_mps": "App_V_RMSE",
        "apparent_vector_RMSE_mps": "Apparent_wind_vector_RMSE",
        "AWS_RMSE_mps": "AWS_RMSE",
        "HDG_MAE_deg": "HDG_MAE",
        "HDG_RMSE_deg": "HDG_RMSE",
        "AWA_MAE_deg": "AWA_MAE",
        "AWA_RMSE_deg": "AWA_RMSE",
    }

    for metric, short_name in metric_map.items():
        mean_col = f"mean_{metric}"
        std_col = f"std_{metric}"

        if mean_col not in hs2.columns:
            continue

        wide_rows = []
        tex_rows = []

        for model in order:
            g = hs2[hs2["model"] == model]
            if g.empty:
                continue

            raw_row = {"Model": model}
            tex_row = {"Model": model}

            for h in HORIZONS:
                q = g[g["horizon_min"] == int(h)]
                if q.empty:
                    raw_row[f"{h} min mean"] = np.nan
                    raw_row[f"{h} min std"] = np.nan
                    tex_row[f"{h} min"] = "--"
                    continue

                rr = q.iloc[0]
                mean_val = float(rr[mean_col])
                std_val = float(rr[std_col]) if std_col in rr.index else 0.0

                raw_row[f"{h} min mean"] = mean_val
                raw_row[f"{h} min std"] = std_val

                digits = 2 if metric.endswith("_deg") else 4
                tex_row[f"{h} min"] = fmt(mean_val, std_val, digits)

            wide_rows.append(raw_row)
            tex_rows.append(tex_row)

        wide_df = pd.DataFrame(wide_rows)
        wide_df.to_csv(
            tables_dir / f"All_models_{short_name}_by_horizon.csv",
            index=False,
            encoding="utf-8-sig",
        )

        # LaTeX output is also generated for direct inspection/use.
        unit = (
            "deg"
            if metric.endswith("_deg")
            else "m s$^{-1}$"
        )
        latex = pd.DataFrame(tex_rows).to_latex(
            index=False,
            escape=False,
            column_format="lccccc",
            caption=(
                f"Horizon-wise {short_name.replace('_', ' ')} "
                f"({unit}) on the frozen SD1090 internal-evaluation set."
            ),
            label=f"tab:internal_{short_name.lower()}_horizons",
        )
        (
            tables_dir / f"All_models_{short_name}_by_horizon.tex"
        ).write_text(latex, encoding="utf-8")

    # Final controlled branch ablation, horizon resolved.
    branch_order = [
        "Dual Ridge",
        "Wind enhanced",
        "Motion enhanced",
        "Physics-Compact",
    ]
    branch = hs2[
        hs2["model"].isin(branch_order)
    ].copy()

    if not branch.empty:
        rows = []
        for h in HORIZONS:
            gh = branch[branch["horizon_min"] == int(h)]
            dual_q = gh[gh["model"] == "Dual Ridge"]
            if dual_q.empty:
                continue
            dual = float(
                dual_q["mean_apparent_vector_RMSE_mps"].iloc[0]
            )

            for model in branch_order:
                q = gh[gh["model"] == model]
                if q.empty:
                    continue
                rr = q.iloc[0]
                val = float(rr["mean_apparent_vector_RMSE_mps"])
                std = float(rr["std_apparent_vector_RMSE_mps"])
                gain = (dual - val) / dual * 100.0
                rows.append(
                    {
                        "Horizon (min)": int(h),
                        "Variant": model,
                        "AW RMSE mean (m/s)": val,
                        "AW RMSE std (m/s)": std,
                        "Gain vs Dual Ridge (%)": gain,
                    }
                )

        pd.DataFrame(rows).to_csv(
            tables_dir / "Branch_ablation_AW_RMSE_ALL_horizons.csv",
            index=False,
            encoding="utf-8-sig",
        )


def fmt(mean, std, digits=4):
    if not np.isfinite(mean):
        return "--"
    if not np.isfinite(std) or abs(std) < 5e-12:
        return f"{mean:.{digits}f}"
    return f"{mean:.{digits}f} $\\pm$ {std:.{digits}f}"


