def fit_final_ridges(frozen):
    Xtr = np.asarray(frozen["train"]["X"], dtype=np.float32)
    Xte = np.asarray(frozen["test"]["X"], dtype=np.float32)
    # use physical y_raw when available, matching the final plotting/audit code
    if "y_raw" in frozen["train"]:
        ytr = np.asarray(frozen["train"]["y_raw"], dtype=np.float32)
    else:
        ytr = frozen["test_y_raw"][:0]  # never reached in the normal frozen dataset
        raise RuntimeError("train.npz must contain y_raw for exact final Ridge reconstruction")

    wind = Ridge(alpha=FINAL_WIND_ALPHA, fit_intercept=True)
    wind.fit(Xtr[:, :, 0:4].reshape(len(Xtr), -1), ytr[:, :, 0:2].reshape(len(ytr), -1))
    pred_w = wind.predict(Xte[:, :, 0:4].reshape(len(Xte), -1)).reshape(-1, 5, 2)

    joint = Ridge(alpha=FINAL_MOTION_ALPHA, fit_intercept=True)
    joint.fit(Xtr.reshape(len(Xtr), -1), ytr.reshape(len(ytr), -1))
    pred_j = joint.predict(Xte.reshape(len(Xte), -1)).reshape(-1, 5, 6)
    pred_m = pred_j[:, :, 2:6]
    q = pred_m[:, :, 2:4]
    qn = np.sqrt(np.sum(q*q, axis=-1, keepdims=True))
    pred_m[:, :, 2:4] = q / np.maximum(qn, 1e-12)
    return pred_w.astype(np.float32), pred_m.astype(np.float32)


def make_joint(wind, motion):
    out = np.empty((len(wind), 5, 6), dtype=np.float32)
    out[..., 0:2] = wind
    out[..., 2:6] = motion
    return out


def build_persistence(frozen):
    Xz = np.asarray(frozen["test"]["X"], dtype=np.float64)
    Xraw = Xz * frozen["feature_std"][None, None, :] + frozen["feature_mean"][None, None, :]
    last = Xraw[:, -1, :]
    U, V, SOG = last[:, 0], last[:, 1], last[:, 4]
    cs, cc = normalize_sincos(last[:, 5], last[:, 6])
    hs, hc = normalize_sincos(last[:, 7], last[:, 8])
    state = np.stack([U, V, SOG*cs, SOG*cc, hs, hc], axis=-1)
    return np.repeat(state[:, None, :], 5, axis=1).astype(np.float32)



