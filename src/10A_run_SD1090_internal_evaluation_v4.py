def apparent_from_joint(y):
    y = np.asarray(y, dtype=np.float64)
    if y.ndim != 3 or y.shape[1:] != (5, 6):
        raise ValueError(f"Expected [N,5,6], got {y.shape}")
    return y[..., 0:2] - y[..., 2:4]


def normalize_sincos(s, c):
    n = np.maximum(np.sqrt(s*s + c*c), 1e-12)
    return s/n, c/n


def heading_deg(y):
    s, c = normalize_sincos(y[..., 4], y[..., 5])
    return np.mod(np.degrees(np.arctan2(s, c)), 360.0)


def awa_aws(y):
    app = apparent_from_joint(y)
    ae, an = app[..., 0], app[..., 1]
    s, c = normalize_sincos(y[..., 4], y[..., 5])
    af = ae*s + an*c
    ast = ae*c - an*s
    awa = np.degrees(np.arctan2(-ast, -af))
    awa = (awa + 180.0) % 360.0 - 180.0
    aws = np.sqrt(ae*ae + an*an)
    return awa, aws


def circular_abs_error_deg(true_deg, pred_deg):
    d = (np.asarray(pred_deg) - np.asarray(true_deg) + 180.0) % 360.0 - 180.0
    return np.abs(d)


def vector_rmse(true, pred):
    e = np.asarray(pred, float) - np.asarray(true, float)
    return float(np.sqrt(np.mean(np.sum(e*e, axis=-1))))


def scalar_rmse(true, pred):
    e = np.asarray(pred, float) - np.asarray(true, float)
    return float(np.sqrt(np.mean(e*e)))


def metrics_per_horizon(truth, pred):
    """
    Comprehensive physical-unit metrics at EACH forecast horizon.

    Saved metrics include component-wise, vector, scalar-speed, heading,
    and apparent-wind errors.  The five-horizon averages produced elsewhere
    are summaries only; the horizon-resolved values are always retained.
    """
    truth = np.asarray(truth, dtype=np.float64)
    pred = np.asarray(pred, dtype=np.float64)

    if truth.shape != pred.shape or truth.shape[1:] != (5, 6):
        raise RuntimeError(
            f"truth/pred mismatch: {truth.shape} vs {pred.shape}"
        )

    t_wind = truth[..., 0:2]
    p_wind = pred[..., 0:2]
    t_vessel = truth[..., 2:4]
    p_vessel = pred[..., 2:4]

    t_app = t_wind - t_vessel
    p_app = p_wind - p_vessel

    t_ws = np.linalg.norm(t_wind, axis=-1)
    p_ws = np.linalg.norm(p_wind, axis=-1)
    t_sog = np.linalg.norm(t_vessel, axis=-1)
    p_sog = np.linalg.norm(p_vessel, axis=-1)
    t_aws = np.linalg.norm(t_app, axis=-1)
    p_aws = np.linalg.norm(p_app, axis=-1)

    t_hdg = heading_deg(truth)
    p_hdg = heading_deg(pred)
    t_awa, _ = awa_aws(truth)
    p_awa, _ = awa_aws(pred)

    rows = []

    for j, h in enumerate(HORIZONS):
        hdg_abs = circular_abs_error_deg(
            t_hdg[:, j],
            p_hdg[:, j],
        )
        awa_abs = circular_abs_error_deg(
            t_awa[:, j],
            p_awa[:, j],
        )

        rows.append(
            {
                "horizon_min": int(h),

                "U_RMSE_mps": scalar_rmse(
                    t_wind[:, j, 0],
                    p_wind[:, j, 0],
                ),
                "V_RMSE_mps": scalar_rmse(
                    t_wind[:, j, 1],
                    p_wind[:, j, 1],
                ),
                "wind_vector_RMSE_mps": vector_rmse(
                    t_wind[:, j, :],
                    p_wind[:, j, :],
                ),
                "wind_speed_RMSE_mps": scalar_rmse(
                    t_ws[:, j],
                    p_ws[:, j],
                ),

                "Vessel_East_RMSE_mps": scalar_rmse(
                    t_vessel[:, j, 0],
                    p_vessel[:, j, 0],
                ),
                "Vessel_North_RMSE_mps": scalar_rmse(
                    t_vessel[:, j, 1],
                    p_vessel[:, j, 1],
                ),
                "vessel_vector_RMSE_mps": vector_rmse(
                    t_vessel[:, j, :],
                    p_vessel[:, j, :],
                ),
                "SOG_RMSE_mps": scalar_rmse(
                    t_sog[:, j],
                    p_sog[:, j],
                ),

                "App_U_RMSE_mps": scalar_rmse(
                    t_app[:, j, 0],
                    p_app[:, j, 0],
                ),
                "App_V_RMSE_mps": scalar_rmse(
                    t_app[:, j, 1],
                    p_app[:, j, 1],
                ),
                "apparent_vector_RMSE_mps": vector_rmse(
                    t_app[:, j, :],
                    p_app[:, j, :],
                ),
                "AWS_RMSE_mps": scalar_rmse(
                    t_aws[:, j],
                    p_aws[:, j],
                ),

                "HDG_MAE_deg": float(np.mean(hdg_abs)),
                "HDG_RMSE_deg": float(
                    np.sqrt(np.mean(hdg_abs * hdg_abs))
                ),
                "AWA_MAE_deg": float(np.mean(awa_abs)),
                "AWA_RMSE_deg": float(
                    np.sqrt(np.mean(awa_abs * awa_abs))
                ),
            }
        )

    return pd.DataFrame(rows)


