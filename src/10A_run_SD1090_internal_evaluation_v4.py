def sliding_mean(x, window):
    x = np.asarray(x, dtype=np.float64)
    cs = np.concatenate([[0.0], np.cumsum(x)])
    return (cs[window:] - cs[:-window]) / float(window)


def variability_score(uv, window):
    u, v = uv[:, 0], uv[:, 1]
    mu_u, mu_v = sliding_mean(u, window), sliding_mean(v, window)
    var_u = sliding_mean(u*u, window) - mu_u*mu_u
    var_v = sliding_mean(v*v, window) - mu_v*mu_v
    return np.sqrt(np.maximum(var_u + var_v, 0.0))


def select_common_interval(truth, target_time_ns, window):
    if target_time_ns is None:
        raise RuntimeError("test.npz must contain target_time_ns for exact same-time 1/5/10 min figures")
    tt = np.asarray(target_time_ns, dtype=np.int64)
    if tt.shape != (len(truth), 5):
        raise RuntimeError(f"Unexpected target_time_ns shape: {tt.shape}")
    j10 = int(np.where(HORIZONS == 10)[0][0])
    obs10 = apparent_from_joint(truth)[:, j10, :]
    var = variability_score(obs10, window)
    common_first = max(int(tt[0, j]) for j in range(5))
    common_last = min(int(tt[-1, j]) for j in range(5))
    score = np.full_like(var, -np.inf)
    for start in range(len(var)):
        stop = start + window - 1
        if int(tt[start, j10]) >= common_first and int(tt[stop, j10]) <= common_last:
            score[start] = var[start]
    if not np.isfinite(score).any():
        raise RuntimeError("No common plotting interval across all horizons")
    start = int(np.argmax(score))
    return {
        "window_samples": int(window),
        "start_time_ns": int(tt[start, j10]),
        "end_time_ns": int(tt[start + window - 1, j10]),
        "reference_start_index_10min": start,
        "observed_variability_score": float(var[start]),
    }


def aligned_indices(times, start_ns, window):
    times = np.asarray(times, dtype=np.int64)
    i = int(np.searchsorted(times, start_ns, side="left"))
    if i >= len(times) or int(times[i]) != int(start_ns):
        raise RuntimeError("Exact common start timestamp cannot be aligned across horizons")
    if i + window > len(times):
        raise RuntimeError("Aligned plotting interval exceeds available data")
    return i, i + window


def plot_one_horizon(figures_dir: Path, truth, pred_mean, times, interval, horizon):
    j = int(np.where(HORIZONS == horizon)[0][0])
    start, stop = aligned_indices(times[:, j], interval["start_time_ns"], interval["window_samples"])
    obs = apparent_from_joint(truth)[start:stop, j, :]
    pred_app = {m: apparent_from_joint(p)[start:stop, j, :] for m, p in pred_mean.items()}
    t = np.arange(stop - start, dtype=float) / 60.0

    fig, axes = plt.subplots(2, 1, figsize=(7.15, 4.15), sharex=True, constrained_layout=False)
    fig.subplots_adjust(left=0.095, right=0.992, bottom=0.12, top=0.86, hspace=0.10)
    model_order = ["Physics-Compact", "DLinear", "TimeMixer", "iTransformer", "PatchTST"]

    axes[0].plot(t, obs[:, 0], color=COLORS["Observed"], linewidth=1.00, linestyle="-", label="Observed", zorder=6)
    for name in model_order:
        axes[0].plot(t, pred_app[name][:, 0], color=COLORS[name], linewidth=0.74, linestyle="-", label=name, alpha=0.97, zorder=4)
    axes[0].set_ylabel(r"Apparent-wind $U_{\mathrm{app}}$ (m s$^{-1}$)")
    panel_label(axes[0], "(a)")
    clean_axis(axes[0])

    axes[1].plot(t, obs[:, 1], color=COLORS["Observed"], linewidth=1.00, linestyle="-", label="Observed", zorder=6)
    for name in model_order:
        axes[1].plot(t, pred_app[name][:, 1], color=COLORS[name], linewidth=0.74, linestyle="-", label=name, alpha=0.97, zorder=4)
    axes[1].set_xlabel("Time within selected internal-evaluation interval (h)")
    axes[1].set_ylabel(r"Apparent-wind $V_{\mathrm{app}}$ (m s$^{-1}$)")
    panel_label(axes[1], "(b)")
    clean_axis(axes[1])

    handles, labels = axes[0].get_legend_handles_labels()
    fig.legend(handles, labels, loc="upper center", bbox_to_anchor=(0.5, 0.985), ncol=6,
               frameon=False, fontsize=6.8, columnspacing=0.95, handlelength=2.0, handletextpad=0.38)
    save_both(fig, figures_dir / f"Fig_internal_appUV_h{horizon:02d}min")

    rows = []
    for name, p in pred_app.items():
        e = p - obs
        rows.append({
            "model": name, "horizon_min": int(horizon),
            "Uapp_RMSE_mps": float(np.sqrt(np.mean(e[:,0]**2))),
            "Vapp_RMSE_mps": float(np.sqrt(np.mean(e[:,1]**2))),
            "AppVector_RMSE_mps": float(np.sqrt(np.mean(np.sum(e*e, axis=1)))),
            "start_index_at_horizon": start, "stop_index_exclusive": stop,
        })
    return pd.DataFrame(rows)


