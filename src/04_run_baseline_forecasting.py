# -*- coding: utf-8 -*-
"""
04_run_baseline_forecasting.py

Baseline forecasting experiments for the validated Saildrone SD1090 dataset.

Baseline models
---------------
1. Persistence
   The future U/V vector is assumed to remain equal to the last observed U/V
   vector at the end of the 60-min input context.

2. Ridge regression
   The complete standardized input sequence is flattened:
       [lookback, features] -> [lookback * features]
   and a multi-output ridge model predicts all standardized future U/V targets:
       [horizons, 2] -> [horizons * 2]

Protocol
--------
- Requires a forecasting dataset produced by 02_build_forecasting_dataset.py.
- By default requires a VALIDATION_PASSED.flag generated by
  03_validate_forecasting_dataset.py.
- Ridge alpha is selected ONLY on the validation split.
- Test data are not used for model fitting or hyperparameter selection.
- The selected Ridge model remains fitted on TRAIN only, keeping the protocol
  aligned with later neural-network experiments that use validation for model
  selection/early stopping.
- Standardization is inherited unchanged from the frozen dataset and therefore
  remains TRAIN-only.

Primary selection criterion
---------------------------
Mean vector RMSE over all forecast horizons on the validation split:

    vector_RMSE(h) = sqrt(mean[(U_hat-U)^2 + (V_hat-V)^2])

The validation score for alpha selection is the arithmetic mean across horizons.

Metrics reported per horizon
----------------------------
- U_RMSE
- V_RMSE
- vector_RMSE
- U_MAE
- V_MAE
- vector_MAE
- speed_RMSE
- speed_MAE
- R2_U
- R2_V
- R2_mean
- skill_vs_persistence

where:
    speed = sqrt(U^2 + V^2)
    skill = 1 - model_vector_RMSE / persistence_vector_RMSE

Outputs
-------
baseline_manifest.json
ridge_alpha_search.csv
metrics_per_horizon.csv
metrics_summary.csv
validation_predictions.npz
test_predictions.npz
ridge_model.joblib
baseline_report.txt
figures/
    01_test_vector_rmse.png/pdf
    02_test_speed_rmse.png/pdf
    03_test_ridge_skill.png/pdf
    04_test_10min_speed_timeseries.png/pdf

Usage example
-------------
python 04_run_baseline_forecasting.py ^
    --dataset-dir "D:\\...\\SD1090_TPOS2024_Forecasting_v0_1_2" ^
    --output "D:\\...\\baseline_v0_1" ^
    --alpha-grid "0.01,0.1,1,10,100" ^
    --plots
"""

